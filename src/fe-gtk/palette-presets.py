"""Writes palette-presets.h: the color schemes in Preferences > Colors.

usage: palette-presets.py DIR > palette-presets.h
DIR is the windowsterminal/ folder of
https://github.com/mbadolato/iTerm2-Color-Schemes (MIT licensed).
"""
