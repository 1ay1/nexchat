import os
import sys

# light, dark: shown once, picks the one that matches the system
PAIRS = [
    ("Adwaita", "Adwaita", "Adwaita Dark"),
    ("Atom One", "Atom One Light", "Atom One Dark"),
    ("Ayu", "Ayu Light", "Ayu"),
    ("Catppuccin", "Catppuccin Latte", "Catppuccin Mocha"),
    ("Everforest", "Everforest Light Med", "Everforest Dark Med"),
    ("Flexoki", "Flexoki Light", "Flexoki Dark"),
    ("GitHub", "GitHub Light Default", "GitHub Dark Default"),
    ("Gruvbox", "Gruvbox Light", "Gruvbox Dark"),
    ("Gruvbox Material", "Gruvbox Material Light", "Gruvbox Material Dark"),
    ("Kanagawa", "Kanagawa Lotus", "Kanagawa Wave"),
    ("Melange", "Melange Light", "Melange Dark"),
    ("Modus", "Modus Operandi", "Modus Vivendi"),
    ("Monokai Pro", "Monokai Pro Light", "Monokai Pro"),
    ("Night Owl", "Light Owl", "Night Owl"),
    ("Nightfox", "Dayfox", "Nightfox"),
    ("Nord", "Nord Light", "Nord"),
    ("One Half", "One Half Light", "One Half Dark"),
    ("Rose Pine", "Rose Pine Dawn", "Rose Pine"),
    ("Selenized", "Selenized Light", "Selenized Dark"),
    ("Solarized", "iTerm2 Solarized Light", "iTerm2 Solarized Dark"),
    ("Tango", "Builtin Tango Light", "Builtin Tango Dark"),
    ("Tokyo Night", "TokyoNight Day", "TokyoNight"),
    ("Tomorrow", "Tomorrow", "Tomorrow Night"),
    ("Xcode", "Xcode Light", "Xcode Dark"),
    ("Zenbones", "Zenbones Light", "Zenbones Dark"),
]

# mIRC colour 0-15 <- terminal colour (orange has none: red/yellow mixed)
MIRC_FROM = ["brightWhite", "black", "blue", "green", "red", "brightRed", "purple", None,
             "yellow", "brightGreen", "cyan", "brightCyan", "brightBlue", "brightPurple",
             "brightBlack", "white"]

# IRC's own: mIRC 0-15, then background, foreground, selection, selected text
MIRC = {
    "mIRC": ["ffffff", "000000", "00007f", "009300", "ff0000", "7f0000", "9c009c", "fc7f00",
             "ffff00", "00fc00", "009393", "00ffff", "0000fc", "ff00ff", "7f7f7f", "d2d2d2",
             "ffffff", "000000", "0a246a", "ffffff"],
    "HexChat 2.9": ["cccccc", "000000", "3636b2", "2a8c2a", "c33b3b", "c73232", "80267f", "66361f",
                    "d9a641", "3dcc3d", "195555", "2e8c74", "4545e6", "b037b0", "4c4c4c", "959595",
                    "f0f0f0", "000000", "356ec1", "ffffff"],
}


def mix(a, b):
    return sum(((((a >> s) & 255) + ((b >> s) & 255)) // 2) << s for s in (16, 8, 0))


def luma(c):
    return 0.299 * ((c >> 16) & 255) + 0.587 * ((c >> 8) & 255) + 0.114 * (c & 255)


def hexval(s):
    s = s.lstrip("#")
    if len(s) == 3:
        s = "".join(c * 2 for c in s)
    return int(s[:6], 16)


def main():
    src = sys.argv[1]
    schemes = {}
    for f in sorted(os.listdir(src)):
        if not f.endswith(".json"):
            continue
        d = json.load(open(os.path.join(src, f)))
        cols = [hexval(d[k]) if k else mix(hexval(d["red"]), hexval(d["yellow"])) for k in MIRC_FROM]
        fg = hexval(d["foreground"])
        bg = hexval(d["background"])
        sel = hexval(d["selectionBackground"])
        # some schemes select with the text colour itself
        seltext = fg if abs(luma(fg) - luma(sel)) >= abs(luma(bg) - luma(sel)) else bg
        cols += [bg, fg, sel, seltext]
        schemes[d["name"]] = cols
    for name, cols in MIRC.items():
        schemes[name] = [int(c, 16) for c in cols]
    for _, light, dark in PAIRS:
        assert light in schemes and dark in schemes, (light, dark)

    names = sorted(schemes, key=lambda n: n.lower())
    index = {n: i for i, n in enumerate(names)}
    out = sys.stdout
    out.write("/* generated by palette-presets.py, do not edit. Terminal schemes from\n"
              "   https://github.com/mbadolato/iTerm2-Color-Schemes, MIT license,\n"
              "   Copyright (c) 2011 to Present Mark Badolato */\n\n")
    out.write("static const nx_scheme nx_schemes[] = {\n")
    for n in names:
        esc = n.replace("\\", "\\\\").replace('"', '\\"')
        out.write('\t{ "%s", { %s } },\n' % (esc, ", ".join("0x%06x" % c for c in schemes[n])))
    out.write("};\n\n")
    out.write("static const nx_scheme_pair nx_scheme_pairs[] = {\n")
    for label, light, dark in PAIRS:
        out.write('\t{ "%s", %d, %d },\n' % (label, index[light], index[dark]))
    out.write("};\n")


main()
